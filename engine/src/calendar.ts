/** 调休上班日（周末上班） */
const EXTRA_WORKDAYS = new Set<string>([
  '2026-01-04', // 元旦调休（周日上班）
  '2026-02-14', '2026-02-28', // 春节调休（周六上班）
  '2026-05-09', // 劳动节调休（周六上班）
  '2026-09-20', '2026-10-10', // 国庆调休（周日/周六上班）
]);

export type DayType = 'workday' | 'weekend' | 'holiday';

/** 日历类型：法定节假日 > 调休上班 > 周末 > 工作日 */
export function dayType(date: string): DayType {
  if (HOLIDAYS.has(date)) return 'holiday';
  if (EXTRA_WORKDAYS.has(date)) return 'workday';
  const dow = dayOfWeek(date);
  return dow === 0 || dow === 6 ? 'weekend' : 'workday';
}
